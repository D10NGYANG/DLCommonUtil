package com.d10ng.common.test

import com.d10ng.common.base.toByteArray
import com.d10ng.common.base.toDouble
import com.d10ng.common.base.toStringWithMaxDecimal
import kotlin.test.*

class DoubleTest {

    @Test
    fun testToString() {
        // 正常情况
        val value = 0.1234567
        assertEquals("0.1", value.toStringWithMaxDecimal(1))
        assertEquals("0.12", value.toStringWithMaxDecimal(2))
        assertEquals("0.123", value.toStringWithMaxDecimal(3))
        assertEquals("0.1234", value.toStringWithMaxDecimal(4))
        assertEquals("0.12345", value.toStringWithMaxDecimal(5))
        assertEquals("0.1234567", value.toStringWithMaxDecimal(7))
        assertEquals("0.1234567", value.toStringWithMaxDecimal(8))

        // 边界情况
        assertEquals("0", value.toStringWithMaxDecimal(0))

        // 异常情况
        assertFails { value.toStringWithMaxDecimal(-1) }
    }

    @Test
    fun testDoubleToByteArray() {
        // 测试正数
        assertContentEquals(byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 0.0.toByteArray())
        assertContentEquals(byteArrayOf(0x3F, 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 1.0.toByteArray())
        assertContentEquals(byteArrayOf(0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 2.0.toByteArray())
        assertContentEquals(byteArrayOf(0x40, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 3.0.toByteArray())
        assertContentEquals(byteArrayOf(0x40, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 4.0.toByteArray())
        assertContentEquals(byteArrayOf(0x40, 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 5.0.toByteArray())
        assertContentEquals(byteArrayOf(0x40, 0x1A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), 6.5.toByteArray())

        // 测试负数
        assertContentEquals(byteArrayOf(0xBF.toByte(), 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), (-1.0).toByteArray())
        assertContentEquals(byteArrayOf(0xC0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), (-2.0).toByteArray())
        assertContentEquals(byteArrayOf(0xC0.toByte(), 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), (-3.0).toByteArray())
        assertContentEquals(byteArrayOf(0xC0.toByte(), 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), (-4.0).toByteArray())
        assertContentEquals(byteArrayOf(0xC0.toByte(), 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), (-5.0).toByteArray())
        assertContentEquals(byteArrayOf(0xC0.toByte(), 0x1A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), (-6.5).toByteArray())

        // 测试特殊值
        assertContentEquals(byteArrayOf(0x7F, 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), Double.POSITIVE_INFINITY.toByteArray())
        assertContentEquals(byteArrayOf(0xFF.toByte(), 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), Double.NEGATIVE_INFINITY.toByteArray())
        assertContentEquals(byteArrayOf(0x7F, 0xF8.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), Double.NaN.toByteArray())
    }

    @Test
    fun testByteArrayToDouble() {
        // 测试正数
        assertEquals(0.0, byteArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(1.0, byteArrayOf(0x3F, 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(2.0, byteArrayOf(0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(3.0, byteArrayOf(0x40, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(4.0, byteArrayOf(0x40, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(5.0, byteArrayOf(0x40, 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(6.5, byteArrayOf(0x40, 0x1A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())

        // 测试负数
        assertEquals(-1.0, byteArrayOf(0xBF.toByte(), 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(-2.0, byteArrayOf(0xC0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(-3.0, byteArrayOf(0xC0.toByte(), 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(-4.0, byteArrayOf(0xC0.toByte(), 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(-5.0, byteArrayOf(0xC0.toByte(), 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())
        assertEquals(-6.5, byteArrayOf(0xC0.toByte(), 0x1A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble())

        // 测试特殊值
        assertTrue(byteArrayOf(0x7F, 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble().isInfinite())
        assertTrue(byteArrayOf(0x7F, 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble() > 0)
        assertTrue(byteArrayOf(0xFF.toByte(), 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble().isInfinite())
        assertTrue(byteArrayOf(0xFF.toByte(), 0xF0.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble() < 0)
        assertTrue(byteArrayOf(0x7F, 0xF8.toByte(), 0x00, 0x00, 0x00, 0x00, 0x00, 0x00).toDouble().isNaN())

        // 测试非8字节的数组
        assertFailsWith<IllegalArgumentException> { byteArrayOf().toDouble() }
        assertFailsWith<IllegalArgumentException> { ByteArray(7) { 0 }.toDouble() }
        assertFailsWith<IllegalArgumentException> { ByteArray(9) { 0 }.toDouble() }
    }
}
